// One reminder as the client sends it. A non-repeating reminder is just a date
// and a time; the repeat fields are ignored unless `recurring` is on.
const reminderSchema = z.object({
  id: z.number().int().optional().nullable(),
  enabled: z.boolean().optional(),
  startDate: z.string().max(10),
  time: z.string().max(5),
  recurring: z.boolean().optional(),
  repeatEvery: z.number().int().optional().nullable(),
  repeatUnit: z.string().max(10).optional().nullable(),
  weekdays: z.array(z.number().int()).max(7).optional().nullable(),
  untilDate: z.string().max(10).optional().nullable()
});

// Normalise one reminder to exactly what goes in the row, or null if it does not
// describe a real moment. Everything the schedule is judged on is written here,
// so this is also what the "did the schedule change?" comparison reads.
function normaliseReminder(input) {
  const startDate = `${input.startDate ?? ""}`.trim();
  const time = `${input.time ?? ""}`.trim();
  if (!isYmd(startDate) || parseHm(time) === null) return null;
  const recurring = input.recurring === true;
  const unit = `${input.repeatUnit ?? "week"}`.toLowerCase();
  const until = `${input.untilDate ?? ""}`.trim();
  return {
    enabled: input.enabled === false ? 0 : 1,
    startDate,
    // Stored as the canonical 'HH:mm' so '9:00' and '09:00' are one occurrence
    // key, not two.
    time: time.length === 4 ? `0${time}` : time,
    recurring: recurring ? 1 : 0,
    repeatEvery: recurring
      ? Math.max(1, Math.min(MAX_REPEAT_EVERY, Number(input.repeatEvery) || 1))
      : 1,
    repeatUnit: recurring && UNITS.has(unit) ? unit : "week",
    weekdays: recurring && unit === "week" && Array.isArray(input.weekdays)
      ? (parseWeekdays(input.weekdays.join(",")).join(",") || null)
      : null,
    // "Until" only means anything for a repeat, and an end before the start is
    // no end at all.
    untilDate: recurring && isYmd(until) && until >= startDate ? until : null
  };
}

// The fields a delivery is keyed on. Two reminders that agree here are the same
// schedule, so the one-shot ledger survives an unrelated edit (renaming, or
// simply pressing Save) instead of re-arming an occurrence already delivered.
function scheduleSignature(r) {
  return [r.startDate, r.time, r.recurring, r.repeatEvery, r.repeatUnit, r.weekdays ?? "", r.untilDate ?? ""].join("|");
}

function signatureOfRow(row) {
  return scheduleSignature({
    startDate: row.start_date,
    time: row.remind_time,
    recurring: row.is_recurring === true || row.is_recurring === 1 ? 1 : 0,
    repeatEvery: row.repeat_every,
    repeatUnit: row.repeat_unit,
    weekdays: row.weekdays,
    untilDate: row.until_date
  });
}

// Replace the reminder list of ONE card. Rows the client still knows the id of
// are updated in place (keeping their ledger when the schedule is unchanged),
// new ones are inserted and the rest are deleted.
router.put("/items/:uid/reminders", asyncHandler(async (req, res) => {
  if (!(await hasReminderTables())) {
    return res.status(503).json({ error: "REMINDERS_NOT_AVAILABLE" });
  }
  const uid = normaliseUid(req.params.uid);
  if (!uid) return res.status(400).json({ error: "INVALID_ITEM_UID" });

  const input = z.object({
    reminders: z.array(reminderSchema).max(MAX_REMINDERS_PER_CARD).optional().default([])
  }).parse(req.body);

  const existing = (await query(
    `SELECT id, start_date, remind_time, is_recurring, repeat_every, repeat_unit,
            weekdays, until_date
     FROM personal_todo_reminders WHERE user_id = @userId AND item_uid = @uid`,
    { userId: req.user.id, uid }
  )).recordset;
  const existingById = new Map(existing.map(row => [row.id, row]));

  const keptIds = [];
  for (const raw of input.reminders) {
    const r = normaliseReminder(raw);
    if (!r) continue; // not a real moment — silently dropped
    const current = raw.id ? existingById.get(Number(raw.id)) : null;
    const params = {
      userId: req.user.id,
      uid,
      enabled: r.enabled,
      startDate: r.startDate,
      time: r.time,
      recurring: r.recurring,
      repeatEvery: r.repeatEvery,
      repeatUnit: r.repeatUnit,
      weekdays: r.weekdays,
      untilDate: r.untilDate
    };
    if (current) {
      // A changed schedule re-arms the reminder; an unchanged one keeps its
      // ledger so today's delivered occurrence is not sent a second time.
      const same = signatureOfRow(current) === scheduleSignature(r);
      await query(
        `UPDATE personal_todo_reminders
         SET enabled = @enabled, start_date = @startDate, remind_time = @time,
             is_recurring = @recurring, repeat_every = @repeatEvery,
             repeat_unit = @repeatUnit, weekdays = @weekdays, until_date = @untilDate,
             -- Editing a card's reminders is proof the card is back.
             orphaned_at = NULL,
             ${same ? "" : "last_sent_key = NULL,"} updated_at = SYSUTCDATETIME()
         WHERE id = @id AND user_id = @userId`,
        { ...params, id: current.id }
      );
      keptIds.push(current.id);
    } else {
      const inserted = (await query(
        `INSERT INTO personal_todo_reminders
           (user_id, item_uid, enabled, start_date, remind_time, is_recurring,
            repeat_every, repeat_unit, weekdays, until_date)
         OUTPUT INSERTED.id
         VALUES (@userId, @uid, @enabled, @startDate, @time, @recurring,
                 @repeatEvery, @repeatUnit, @weekdays, @untilDate)`,
        params
      )).recordset[0];
      keptIds.push(inserted.id);
    }
  }

  const gone = existing.map(row => row.id).filter(id => !keptIds.includes(id));
  for (const id of gone) {
    await query(
      "DELETE FROM personal_todo_reminders WHERE id = @id AND user_id = @userId",
      { id, userId: req.user.id }
    );
  }

  const rows = (await query(
    `SELECT id, item_uid, enabled, start_date, remind_time, is_recurring,
            repeat_every, repeat_unit, weekdays, until_date, last_sent_at
     FROM personal_todo_reminders
     WHERE user_id = @userId AND item_uid = @uid
     ORDER BY start_date, remind_time, id`,
    { userId: req.user.id, uid }
  )).recordset;
  res.json({ reminders: rows.map(reminderJson) });
}));

